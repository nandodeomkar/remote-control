//! Tray icon (SRV-01/SRV-03, Phase 10 redesign): a menu-less `TrayIcon`
//! whose clicks open the custom [`super::flyout::Flyout`] panel — the
//! OS-native muda context menu is fully replaced by the flyout (handoff 1b).
//!
//! **TaskbarCreated re-registration (RESEARCH Pitfall 1 / A1 — CONFIRMED):**
//! `tray-icon` 0.24 handles `TaskbarCreated` internally — its Win32
//! `tray_proc` re-calls `register_tray_icon` on that message (verified
//! against the vendored source, `platform_impl/windows/mod.rs`). No manual
//! re-register/`rebuild()` is needed; the tray survives an Explorer restart
//! as long as the shell thread keeps pumping its winit message loop, which
//! [`super::spawn_shell_thread`] does for the whole process lifetime.
//!
//! **Icon assets:** generated by `tools/gen_icons.py` (quick 260716-ns1
//! branding) — the brand pointer arrow as a white-on-transparent tint mask
//! (`assets/icon/tray_arrow_32.png`, embedded at compile time), tinted per
//! state at runtime. Colors follow the handoff's 1e states: accent blue
//! #38BDF8 (normal), muted gray (paused), error red (warning).

use tray_icon::{Icon, TrayIcon, TrayIconBuilder};

/// White arrow-only brand glyph (RGBA PNG, generated by
/// `tools/gen_icons.py`) — the tint mask every tray state colors.
const TRAY_ARROW_PNG: &[u8] = include_bytes!("../../assets/icon/tray_arrow_32.png");

/// Visual/tooltip state of the tray icon (SRV-01 pause + SRV-04 firewall
/// warning).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrayState {
    /// Running normally, input flowing.
    Normal,
    /// Input paused via the flyout (or the main/settings windows).
    Paused,
    /// The startup self-test found a problem (port-in-use or
    /// firewall-blocked) — SRV-04 / D-06 loud warning.
    Warning,
}

/// The tray icon — deliberately menu-less: clicks route through
/// `TrayIconEvent` to the shell loop, which toggles the flyout.
pub struct Tray {
    icon: TrayIcon,
}

impl Tray {
    /// MUST be called from a thread that is already pumping a win32 message
    /// loop (RESEARCH Pitfall 2/3) — in practice, from
    /// `ApplicationHandler::new_events` on `StartCause::Init`.
    pub fn new() -> tray_icon::Result<Self> {
        let icon = TrayIconBuilder::new()
            .with_icon(icon_for(TrayState::Normal))
            .with_tooltip(tooltip_text(0))
            .build()?;
        Ok(Self { icon })
    }

    /// Sets the tooltip to the device COUNT only — NEVER paired device names
    /// (T-07-20 privacy backstop; the tooltip can be read on a shared
    /// screen). A failed OS-level set is swallowed (never panics the shell
    /// loop over a cosmetic failure).
    pub fn set_tooltip(&self, count: usize) {
        let _ = self.icon.set_tooltip(Some(tooltip_text(count)));
    }

    /// Swaps the icon glyph for the given state (SRV-01 pause / SRV-04
    /// warning). A failed OS-level set is swallowed, same discipline as
    /// [`Tray::set_tooltip`].
    pub fn set_state(&self, state: TrayState) {
        let _ = self.icon.set_icon(Some(icon_for(state)));
    }
}

/// Device-count-only tooltip text (T-07-20 — see [`Tray::set_tooltip`]).
fn tooltip_text(count: usize) -> String {
    match count {
        0 => "Remote Control — no devices connected".to_string(),
        1 => "Remote Control — 1 device connected".to_string(),
        n => format!("Remote Control — {n} devices connected"),
    }
}

/// Build the state's tinted brand-arrow icon (see module docs — glyph from
/// the compile-time-embedded generator output).
fn icon_for(state: TrayState) -> Icon {
    let rgb = match state {
        TrayState::Normal => (0x38, 0xBD, 0xF8),  // handoff accent #38BDF8
        TrayState::Paused => (0x6B, 0x72, 0x80),  // muted token
        TrayState::Warning => (0xFF, 0x6B, 0x6B), // error token
    };
    let (pixels, w, h) = tinted_arrow_pixels(rgb);
    Icon::from_rgba(pixels, w, h).expect("tray_arrow_32.png dimensions are self-consistent")
}

/// Decode the embedded white arrow mask and tint it with the state color:
/// every pixel's RGB is replaced with `rgb` while the source ALPHA is kept —
/// the glyph is white with antialiased alpha edges, so keeping alpha
/// preserves the smooth silhouette. Pure function (no `Icon`/HICON, no OS
/// calls) so it is unit-testable. The `.expect`s follow the same
/// can-never-fire discipline as [`icon_for`]'s `Icon::from_rgba`: the asset
/// is a compile-time-embedded output of `tools/gen_icons.py`, which asserts
/// 32x32 RGBA at generation time.
fn tinted_arrow_pixels(rgb: (u8, u8, u8)) -> (Vec<u8>, u32, u32) {
    // png 0.18's Decoder needs BufRead + Seek — Cursor over the static bytes.
    let decoder = png::Decoder::new(std::io::Cursor::new(TRAY_ARROW_PNG));
    let mut reader = decoder.read_info().expect("tray_arrow_32.png: valid PNG");
    let mut buf =
        vec![0u8; reader.output_buffer_size().expect("tray_arrow_32.png: sane buffer size")];
    let info = reader.next_frame(&mut buf).expect("tray_arrow_32.png: decodable frame");
    assert_eq!(
        info.color_type,
        png::ColorType::Rgba,
        "tray_arrow_32.png must be RGBA (generator guarantees mode)"
    );
    buf.truncate(info.buffer_size());
    for px in buf.chunks_exact_mut(4) {
        px[0] = rgb.0;
        px[1] = rgb.1;
        px[2] = rgb.2;
        // px[3] (alpha) kept from the source mask.
    }
    (buf, info.width, info.height)
}

#[cfg(test)]
mod tests {
    use super::tinted_arrow_pixels;

    /// The decoded+tinted glyph is 32x32 RGBA, carries at least one fully
    /// opaque pixel in the exact state color, and keeps the background
    /// transparent (corner pixel alpha 0).
    #[test]
    fn tinted_arrow_pixels_tints_rgb_and_keeps_alpha() {
        let accent = (0x38, 0xBD, 0xF8);
        let (buf, w, h) = tinted_arrow_pixels(accent);
        assert_eq!((w, h), (32, 32));
        assert_eq!(buf.len(), 32 * 32 * 4);

        let has_opaque_accent = buf.chunks_exact(4).any(|px| {
            px[3] == 255 && (px[0], px[1], px[2]) == accent
        });
        assert!(has_opaque_accent, "expected at least one opaque accent pixel");

        // Corner (0,0) is outside the centered arrow — transparent background.
        assert_eq!(buf[3], 0, "corner pixel (0,0) must be fully transparent");
    }
}
